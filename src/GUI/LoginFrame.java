private void connectToServer() {

    String nickname = txtNickname.getText().trim();
    String ip = txtServerIP.getText().trim();
    String portText = txtPort.getText().trim();

    if (nickname.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter your nickname!");
        return;
    }

    int port;

    try {
        port = Integer.parseInt(portText);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Invalid port number!");
        return;
    }
    if (port < 1 || port > 65535) {
    JOptionPane.showMessageDialog(
        this,
        "Port must be between 1 and 65535!"
    );
    return;
}
    if (ip.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Please enter the server IP address!"
    );
    return;
}

    btnConnect.setEnabled(false);
    btnConnect.setText("CONNECTING...");

    new SwingWorker<Boolean, Void>() {

        @Override
        protected Boolean doInBackground() {
            chatClient = new ChatClient();
            return chatClient.connect(ip, port, nickname);
        }

             @Override
        protected void done() {
            try {
                if (get()) {
                    ChatRoomFrame room = new ChatRoomFrame(chatClient, nickname);
                    room.setLocationRelativeTo(null);
                    room.setVisible(true);
                    dispose();
                } else {
                    String reason = chatClient.getLastError();
                    if (reason == null || reason.isEmpty()) {
                        reason = "Connection failed! Check your server.";
                    }
                    JOptionPane.showMessageDialog(
                            LoginFrame.this, reason,
                            "Connection failed", JOptionPane.ERROR_MESSAGE);
                }
            } catch (HeadlessException | InterruptedException | ExecutionException e) {
                JOptionPane.showMessageDialog(
                        LoginFrame.this, "Error: " + e.getMessage());
            } finally {
                btnConnect.setEnabled(true);
                btnConnect.setText("CONNECT");
            }
        }

    }.execute();
}

